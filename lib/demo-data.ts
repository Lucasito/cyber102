export const DEMO_SOURCE = "demo";

export async function clearDemo(db: PrismaClient) {
  const { count } = await db.event.deleteMany({ where: { sources: { some: { source: DEMO_SOURCE } } } });
  await db.venue.deleteMany({ where: { events: { none: {} } } });
  return count;
}

